import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

/* Цель сборки задана явно — и это не косметика.

   Без неё Vite считает браузеры свежими, и минификатор CSS переписывает
   `@media (max-width: 700px)` в диапазонную запись `@media (width <= 700px)`.
   Такую запись Safari понимает только с 16.4. На iOS 16.0–16.3 медиазапрос
   недействителен, браузер выбрасывает его целиком — и мобильная вёрстка
   пропадает вся разом: на телефоне открывается десктопная раскладка.

   Поймать это на тестах нельзя: эмуляция устройств в Chrome меняет размер
   экрана и user-agent, но движок остаётся Chrome, а он диапазоны понимает.
   И проверить «другим браузером на айфоне» тоже нельзя: на iOS все браузеры
   обязаны работать на движке Safari, поэтому Chrome и Яндекс там покажут
   ровно то же самое.

   Границу берём по тем возможностям, что сайт уже использует: dvh и
   аспектные соотношения появились в Safari 15.4, ниже опускаться незачем.
   Проверка того, что запись осталась совместимой, — tools/css-compat.mjs. */

const TARGET = ['es2020', 'chrome87', 'edge88', 'firefox78', 'safari15.4']

export default defineConfig({
  plugins: [react()],
  build: {
    target: TARGET,
    // cssTarget по умолчанию наследует target, но лучше не полагаться на
    // умолчание: сломается оно тихо, а последствия — во весь экран.
    cssTarget: TARGET,
  },
})
