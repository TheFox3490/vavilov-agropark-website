import { useEffect } from "react";

/* Заголовок вкладки при переходах внутри приложения.

   Первый заголовок приходит с сервера: nginx вклеивает в <head> метатеги,
   собранные бэкендом, — иначе роботы и мессенджеры, не выполняющие
   JavaScript, увидели бы пустую голову. Но при переходе по ссылке страница
   не перезагружается, и заголовок так и остался бы от первой открытой.
   Этот хук его обновляет.

   Метатеги для карточек ссылок здесь не трогаем: к моменту, когда сработает
   JavaScript, робот уже забрал ответ и ушёл. */

const SITE_NAME = "Центр агроробототехники и VR/AR технологий";

export default function usePageTitle(title) {
  useEffect(() => {
    if (!title) return;
    document.title = title === SITE_NAME ? `${SITE_NAME} — Вавиловский университет` : `${title} — ${SITE_NAME}`;
  }, [title]);
}
