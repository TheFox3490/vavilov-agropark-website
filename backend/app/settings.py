# Длина по месту применения: адрес почты и телефон короткие, документ — нет.
MAX_LENGTHS: dict[str, int] = {
    "legal_privacy_body": 40000,
    "legal_consent_body": 40000,
    "legal_privacy_title": 200,
    "legal_consent_title": 200,
    "contact_address": 300,
    "contact_schedule": 200,
}
DEFAULT_MAX_LENGTH = 255


def all_settings() -> dict[str, str]:
    """Все настройки: сохранённые поверх значений по умолчанию.

    Отсутствующая строка — не ошибка, а «ничего не меняли»: сайт
    показывает значение по умолчанию.
    """
    values = dict(DEFAULTS)
    for row in Setting.query.all():
        if row.key in DEFAULTS:
            values[row.key] = row.value
    return values


def update_settings(data: dict) -> str | None:
    """Сохраняет присланные настройки. Возвращает текст ошибки или None."""
    if not isinstance(data, dict):
        return "Ожидается набор настроек"

    changes: dict[str, str] = {}
    for key, raw in data.items():
        if key not in DEFAULTS:
            # Неизвестные ключи молча пропускаем: так форма админки может
            # присылать себя целиком, не зная о серверных тонкостях.
            continue
        value = "" if raw is None else str(raw).strip()
        limit = MAX_LENGTHS.get(key, DEFAULT_MAX_LENGTH)
        if len(value) > limit:
            return f"Значение «{key}» длиннее {limit} символов"
        changes[key] = value

    for key, value in changes.items():
        row = db.session.get(Setting, key)
        if row is None:
            db.session.add(Setting(key=key, value=value))
        else:
            row.value = value
    db.session.commit()
    return None
